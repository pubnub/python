"""Coverage manifest of the live tier: tests/live/coverage.json, generated, one entry per snippet id per file.

    python -u tests/live/cli.py manifest            writes coverage.json
    python -u tests/live/cli.py manifest --check    fails when coverage.json is stale (also run by cli.py lint)

Keyed by file (path relative to the repository root), then id, because 122 ids exist in both docsets and the docs
address a snippet by file and id. mode: live (a test runs it), compile-only (@compile_only, imported, not run).
`whole_files` lists whole-file samples the docs embed without ids, with the test that runs them.
Things the docs embed that are deliberately not run are in snippet-exceptions.json (hand maintained).
"""
import json

from . import LIVE_DIR, LIVE_REL, snippet_scan

COVERAGE_FILE = LIVE_DIR / 'coverage.json'
EXCEPTIONS_FILE = LIVE_DIR / 'snippet-exceptions.json'
COMMENT = ('GENERATED by python -u tests/live/cli.py manifest from the markers in tests/live. DO NOT EDIT. One entry '
           'per snippet id per file. Deliberate exceptions live in snippet-exceptions.json.')


def build(scan=None):
    files_, snippets = scan or snippet_scan.scan_tier()
    problems, files = [], {}
    for s in snippets:
        if s.mode == 'invalid':
            problems.append(f'{s.file.rel}:{s.region.start}: snippet "{s.id}" is not run by any test, left out')
            continue
        entries = files.setdefault(s.file.rel, {})
        if s.id in entries:
            problems.append(f'{s.file.rel}:{s.region.start}: duplicate snippet id "{s.id}", left out')
            continue
        if s.mode == 'compile-only':
            entries[s.id] = {'mode': 'compile-only', 'reason': s.func.compile_only}
        else:
            entry = {'test': s.test_id}
            if s.roles:
                entry['role'] = ','.join(s.roles)
            entry['mode'] = 'live'
            entries[s.id] = entry
    whole = {}
    for f in files_:
        if f.kind == 'sample' and not f.regions:
            runner = next((t for t in files_ if t.kind == 'test' and f.path.name in t.text), None)
            if runner:
                whole[f.rel] = {'mode': 'live', 'test_file': runner.rel}
    manifest = {
        '$comment': COMMENT,
        'files': {k: dict(sorted(v.items())) for k, v in sorted(files.items())},
        'whole_files': dict(sorted(whole.items())),
    }
    return manifest, problems


def serialize(manifest):
    return json.dumps(manifest, indent=2) + '\n'


def read():
    return json.loads(COVERAGE_FILE.read_text()) if COVERAGE_FILE.exists() else None


def load_exceptions():
    if not EXCEPTIONS_FILE.exists():
        return {}
    return json.loads(EXCEPTIONS_FILE.read_text())


def check_exceptions(data=None):
    data = load_exceptions() if data is None else data
    problems, seen = [], set()
    for i, e in enumerate(data.get('exceptions', [])):
        where = f'snippet-exceptions.json entry {i + 1} ({e.get("path", "?")})'
        if not isinstance(e.get('path'), str) or not e['path'].startswith(LIVE_REL + '/'):
            problems.append(f'{where}: "path" must be a {LIVE_REL}/... path')
        if not isinstance(e.get('reason'), str) or len(e['reason'].strip()) < 10:
            problems.append(f'{where}: "reason" is required')
        ids = e.get('ids')
        if ids is not None and (not isinstance(ids, list) or not ids or not all(isinstance(x, str) for x in ids)):
            problems.append(f'{where}: "ids" must be a non-empty list of strings, or absent')
        for ident in ids or ['*']:
            key = (e.get('path'), ident)
            if key in seen:
                problems.append(f'{where}: {ident} is listed twice')
            seen.add(key)
    for i, e in enumerate(data.get('one_sided', [])):
        where = f'snippet-exceptions.json one_sided entry {i + 1}'
        if e.get('docset') not in ('sync', 'asyncio') or not isinstance(e.get('page'), str):
            problems.append(f'{where}: needs "docset" (sync or asyncio) and "page"')
        if not isinstance(e.get('reason'), str) or len(e['reason'].strip()) < 10:
            problems.append(f'{where}: "reason" is required')
    return problems


def totals(manifest):
    out = {'live': 0, 'compile-only': 0}
    for entries in manifest['files'].values():
        for entry in entries.values():
            out[entry['mode']] += 1
    return out


def main(argv=()):
    manifest, problems = build()
    problems += check_exceptions()
    text = serialize(manifest)
    t = totals(manifest)
    summary = (f'{sum(t.values())} snippets (live {t["live"]}, compile-only {t["compile-only"]}) in '
               f'{len(manifest["files"])} files, {len(manifest["whole_files"])} whole-file samples')
    for p in problems:
        print('manifest:', p)
    failed = bool(problems)
    if '--check' in argv:
        current = COVERAGE_FILE.read_text() if COVERAGE_FILE.exists() else None
        if current == text:
            print(f'manifest: coverage.json is up to date, {summary}')
        else:
            failed = True
            print('manifest: coverage.json is stale. Run: python -u tests/live/cli.py manifest')
    else:
        COVERAGE_FILE.write_text(text)
        print(f'manifest: wrote coverage.json, {summary}')
    return 1 if failed else 0
